import { test, expect } from 'vitest';
import { formatStandaloneSvg, getExportFilename } from '../src/ui/export';

test('getExportFilename produces safe filenames without regex content', () => {
  expect(getExportFilename('final', undefined, 'svg')).toBe('nfa-final.svg');
  expect(getExportFilename('final', undefined, 'dot')).toBe('nfa-final.dot');
  expect(getExportFilename('flat', 2, 'svg')).toBe('nfa-step-2-flat.svg');
  expect(getExportFilename('flat', 5, 'dot')).toBe('nfa-step-5-flat.dot');
  expect(getExportFilename('textbook', 4, 'svg')).toBe('nfa-step-4-textbook.svg');
  expect(getExportFilename('textbook', 1, 'dot')).toBe('nfa-step-1-textbook.dot');
});

test('formatStandaloneSvg strips existing XML prolog, DOCTYPE, and comments, and emits exactly one XML declaration', () => {
  const rawGraphvizSvg = `<?xml version="1.0" encoding="UTF-8" standalone="no"?>
<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN"
 "http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd">
<!-- Generated by graphviz version 16.1.0 (20260904.0139)
 -->
<!-- Title: G Pages: 1 -->
<svg width="62pt" height="116pt"
 viewBox="0.00 0.00 62.00 116.00" xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink">
<g id="graph0" class="graph" transform="scale(1 1) rotate(0) translate(4 112)">
<polygon fill="white" stroke="none" points="-4,4 -4,-112 58,-112 58,4 -4,4"/>
</g>
</svg>`;

  const formatted = formatStandaloneSvg(rawGraphvizSvg);
  expect(formatted.startsWith('<?xml version="1.0" encoding="UTF-8"?>\n')).toBe(true);

  // Exactly one XML declaration
  const declMatches = formatted.match(/<\?xml\b/g);
  expect(declMatches).not.toBeNull();
  expect(declMatches!.length).toBe(1);

  // No DOCTYPE
  expect(formatted).not.toContain('<!DOCTYPE');

  // No comments
  expect(formatted).not.toContain('<!-- Generated by graphviz');

  // Contains xmlns and xmlns:xlink
  expect(formatted).toContain('xmlns="http://www.w3.org/2000/svg"');
  expect(formatted).toContain('xmlns:xlink="http://www.w3.org/1999/xlink"');

  // Preserves width and height
  expect(formatted).toContain('width="62pt"');
  expect(formatted).toContain('height="116pt"');

  // Contains opaque white background rect as first child of <svg>
  expect(formatted).toMatch(/<svg[^>]*>\s*<rect\s+width="100%"\s+height="100%"\s+fill="#ffffff"\s*\/>/);
});

test('formatStandaloneSvg is idempotent', () => {
  const rawSvg = `<svg width="100" height="80" viewBox="0 0 100 80" xmlns="http://www.w3.org/2000/svg"><circle cx="50" cy="40" r="30"/></svg>`;
  const firstPass = formatStandaloneSvg(rawSvg);
  const secondPass = formatStandaloneSvg(firstPass);
  expect(secondPass).toBe(firstPass);
});

test('formatStandaloneSvg derives width and height from viewBox if missing', () => {
  const rawSvg = `<svg viewBox="0.00 0.00 120.00 90.00"><circle cx="10" cy="10" r="5"/></svg>`;
  const formatted = formatStandaloneSvg(rawSvg);
  expect(formatted).toContain('width="160"'); // 120 * (4/3) = 160
  expect(formatted).toContain('height="120"'); // 90 * (4/3) = 120
  expect(formatted).toContain('xmlns="http://www.w3.org/2000/svg"');
  expect(formatted).toContain('xmlns:xlink="http://www.w3.org/1999/xlink"');
});
